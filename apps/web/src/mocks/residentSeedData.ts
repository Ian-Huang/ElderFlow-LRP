export function transformRawResident(raw: RawResidentJson, index: number): Resident {
  const pipes = parsePipesString(raw['管路']);
  const hasThree = isThreePipe(pipes);
  const rawBed = raw['床位']?.trim() || '';
  const rawId = raw['住民編號']?.trim() || `RES-${String(index + 1).padStart(3, '0')}`;

  return {
    residentId: rawId,
    name: raw['姓名']?.trim() || '未命名',
    gender: raw['性別'] === '女' ? 'Female' : 'Male',
    dateOfBirth: rocToIso(raw['生日']) || '1950-01-01',
    address: raw['通訊地']?.trim() || raw['戶籍地址']?.trim() || '台北市',
    householdAddress: raw['戶籍地址']?.trim() || '',
    phone: raw['電話']?.trim() || '',
    mobile: raw['手機']?.trim() || '',
    insuranceId: raw['身分證號']?.trim() || '',
    diagnosis: raw['身心障礙類別/等級/到期日']?.trim() || raw['工作史']?.trim() || '常規照護',
    admissionDate: rocToIso(raw['入住日期']) || '2023-01-01',
    specialNeeds: raw['依賴程度']?.trim() || '部分依賴',
    status: 'Active',
    hasThreePipe: hasThree,
    bedNumber: rawBed,
    pipes: pipes,
    identityType: raw['身份別']?.trim() || '一般戶',
    dependencyLevel: raw['依賴程度']?.trim() || '部分依賴',
    emergencyContact: {
      name: raw['第一聯絡姓名']?.trim() || '',
      relationship: raw['第一聯絡關係']?.trim() || '',
      phone: raw['第一聯絡電話']?.trim() || '',
      mobile: raw['第一聯絡手機']?.trim() || '',
      address: raw['第一聯絡地址']?.trim() || '',
      notes: raw['第一聯絡備註']?.trim() || '',
    },
    education: raw['教育程度']?.trim() || '',
    religion: raw['宗教信仰']?.trim() || '',
    workHistory: raw['工作史']?.trim() || '',
    disability: {
      raw: raw['身心障礙類別/等級/到期日']?.trim() || '',
    },
    catastrophicIllness: {
      raw: raw['重大傷病/到期日']?.trim() || '',
    },
    createdAt: '2023-01-01T00:00:00Z',
    updatedAt: '2024-01-15T00:00:00Z',
  };
}

